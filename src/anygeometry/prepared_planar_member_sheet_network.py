def _encode(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':'), allow_nan=False)


def _require(condition, detail):
    if not condition:
        raise GeometryError('prepared planar member Sheet network ' + detail)


def _cross(a, b):
    return (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0])


def _dot(a, b):
    return sum(x*y for x, y in zip(a, b))


def _orient(a, b, c):
    return (b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0])


def _on_segment(p, a, b):
    """Exact: p lies on the closed two-dimensional segment [a, b]."""
    if _orient(a, b, p) != 0:
        return False
    return (min(a[0], b[0]) <= p[0] <= max(a[0], b[0]) and
            min(a[1], b[1]) <= p[1] <= max(a[1], b[1]))


def _inside_polygon(p, loop):
    """Exact crossing parity of one simple loop; p must not be on its boundary."""
    inside = False
    for a, b in loop:
        if (a[1] > p[1]) != (b[1] > p[1]):
            crossing = a[0]+(p[1]-a[1])*(b[0]-a[0])/(b[1]-a[1])
            if p[0] < crossing:
                inside = not inside
    return inside


def _point_in_face(p, loops):
    """Closed outer material minus open hole interiors; exact rationals."""
    if any(_on_segment(p, a, b) for a, b in loops[0]):
        return True
    if not _inside_polygon(p, loops[0]):
        return False
    for hole in loops[1:]:
        if any(_on_segment(p, a, b) for a, b in hole):
            continue
        if _inside_polygon(p, hole):
            return False
    return True


def _segments_meet(a, b, c, d):
    """Exact: two closed segments share at least one point."""
    ab = (_orient(a, b, c), _orient(a, b, d))
    cd = (_orient(c, d, a), _orient(c, d, b))
    return (ab[0]*ab[1] < 0 and cd[0]*cd[1] < 0 or
            _on_segment(c, a, b) or _on_segment(d, a, b) or
            _on_segment(a, c, d) or _on_segment(b, c, d))


def _qualified_loops(loops, check):
    """Refuse degenerate, open, backtracking or nonsimple original loops."""
    for loop in loops:
        check()
        _require(len(loop) >= 3, 'has a degenerate original boundary loop')
        _require(all(a != b for a, b in loop), 'has a degenerate original boundary edge')
        _require(all(first[1] == second[0]
                     for first, second in zip(loop, (*loop[1:], loop[0]))),
                 'has an open original boundary loop')
        count = len(loop)
        for index in range(count):
            a, b = loop[index]
            following = loop[(index+1) % count][1]
            _require(_orient(a, b, following) != 0 or
                     sum((y-x)*(z-y) for x, y, z in zip(a, b, following)) > 0,
                     'has a backtracking original boundary loop')
            for other in range(index+2, count):
                check()
                if other == count-1 and index == 0:
                    continue
                _require(not _segments_meet(a, b, *loop[other]),
                         'has a nonsimple original boundary loop')


def _on_plane(frame, point):
    offset = tuple(value-origin for value, origin in zip(point, frame['origin']))
    return _dot(offset, _cross(frame['u'], frame['v'])) == 0


def _chart_uv(frame, point):
    offset = tuple(value-origin for value, origin in zip(point, frame['origin']))
    return tuple(_dot(offset, row) for row in frame['inverse'])


def _planar_face_charts(source, check, edge_tolerance=None):
    """Exact planar UV charts and literal straight loops of owned Sheet faces.

    Only faces carried by an authored Sheet FaceUse are material owners; a
    sheet-less orphan face can never certify Member material membership.
    """
    owned = set()
    for sheet in source['sheets'].values():
        for key in sheet['face_use_ids']:
            _require(key in source['face_uses'],
                     'has a Sheet FaceUse that is unavailable')
            owned.add(source['face_uses'][key]['face_id'])
    _require(all(face_id in source['faces'] for face_id in owned),
             'has a Sheet FaceUse without an owned authored face')
    charts = {}
    for face_id in sorted(owned):
        check()
        face = source['faces'][face_id]
        _require(face.get('parameterization') is None,
                 'does not qualify original parameterizations')
        support = _decode_surface(face['surface'], strict=True, schema_version=_QUADRIC_VERSION)
        _require(type(support) is Plane, 'requires original Plane faces')
        frame = _frame(support)
        uv_loops, xyz_loops = [], []
        for loop in (face['loop'], *face['holes']):
            uv_loop, xyz_loop = [], []
            for edge_id, forward in loop:
                check()
                edge = source['edges'][edge_id]
                _require(edge['curve'] == {'type': 'straight'},
                         'requires literal Straight original boundaries')
                start = tuple(Fraction(float(x))
                              for x in source['vertices'][edge['start']]['position'])
                end = tuple(Fraction(float(x))
                            for x in source['vertices'][edge['end']]['position'])
                if edge_tolerance is None:
                    _require(_on_plane(frame, start) and _on_plane(frame, end),
                             'has an original boundary vertex off the support plane')
                else:
                    tolerance = edge_tolerance(edge_id)
                    for point in (start,end):
                        uv = _chart_uv(frame,point)
                        projection = tuple(o+uv[0]*u+uv[1]*v for o,u,v in
                                           zip(frame['origin'],frame['u'],frame['v']))
                        _require(_distance_squared(point,projection) <= tolerance**2,
                                 'current child trim leaves its bound support tolerance')
                if not forward:
                    start, end = end, start
                uv_loop.append((_chart_uv(frame, start), _chart_uv(frame, end)))
                xyz_loop.append((start, end))
            uv_loops.append(tuple(uv_loop))
            xyz_loops.append(tuple(xyz_loop))
        _qualified_loops(uv_loops, check)
        charts[face_id] = (frame, tuple(uv_loops), tuple(xyz_loops))
    return charts


def _boundary_events(a, b, loops):
    """Exact segment parameters where [a, b] meets any loop edge."""
    events = set()
    direction = (b[0]-a[0], b[1]-a[1])
    _require(direction != (0,0), 'has a degenerate projected segment')
    for loop in loops:
        for c, d in loop:
            edge = (d[0]-c[0], d[1]-c[1])
            denominator = direction[0]*edge[1]-direction[1]*edge[0]
            if denominator:
                offset = (c[0]-a[0], c[1]-a[1])
                station = (offset[0]*edge[1]-offset[1]*edge[0])/denominator
                other = (offset[0]*direction[1]-offset[1]*direction[0])/denominator
                if 0 <= station <= 1 and 0 <= other <= 1:
                    events.add(station)
            elif _orient(a, b, c) == 0 and _orient(a, b, d) == 0:
                # Collinear overlap: the whole closed contact is boundary.
                length = _dot(direction, direction)
                first = _dot((c[0]-a[0], c[1]-a[1]), direction)/length
                second = _dot((d[0]-a[0], d[1]-a[1]), direction)/length
                low, high = (first, second) if first <= second else (second, first)
                low, high = max(low, Fraction(0)), min(high, Fraction(1))
                if low <= high:
                    events.add(low)
                    events.add(high)
    return events


def _segment_in_face_uv(a, b, loops):
    """Exact: the whole segment lies in the closed face material."""
    if not _point_in_face(a, loops) or not _point_in_face(b, loops):
        return False
    ordered = sorted({Fraction(0), Fraction(1)} | _boundary_events(a, b, loops))
    for low, high in zip(ordered, ordered[1:]):
        middle = (low+high)/2
        if not _point_in_face(((1-middle)*a[0]+middle*b[0],
                               (1-middle)*a[1]+middle*b[1]), loops):
            return False
    return True


def _on_boundary_xyz(point, xyz_loops):
    """Exact: a three-dimensional point lies on one loop edge."""
    for loop in xyz_loops:
        for a, b in loop:
            offset = tuple(p-q for p, q in zip(point, a))
            direction = tuple(p-q for p, q in zip(b, a))
            if not any(_cross(direction, offset)) and 0 <= _dot(offset, direction) <= _dot(direction, direction):
                return True
    return False


def _material_membership(controls, charts, check):
    """Certify one straight carrier segment against the union of materials.

    The complete exact boundary-event decomposition makes every open interval
    between consecutive events homogeneous with respect to every coplanar
    face, so one exact rational midpoint classification per interval decides
    coverage without any sampled acceptance oracle.
    """
    segment = tuple(tuple(Fraction(*value) for value in point) for point in controls)
    coplanar = [(face_id, frame, _chart_uv(frame, segment[0]),
                 _chart_uv(frame, segment[1]), uv_loops)
                for face_id, (frame, uv_loops, _) in sorted(charts.items())
                if _on_plane(frame, segment[0]) and _on_plane(frame, segment[1])]
    _require(coplanar, 'original Member carrier lies in no original support plane')
    events = {Fraction(0), Fraction(1)}
    for face_id, frame, a, b, uv_loops in coplanar:
        check()
        events |= _boundary_events(a, b, uv_loops)
    ordered = sorted(events)
    intervals = []
    for low, high in zip(ordered, ordered[1:]):
        check()
        middle = (low+high)/2
        faces = sorted(face_id for face_id, frame, a, b, uv_loops in coplanar
                       if _point_in_face(((1-middle)*a[0]+middle*b[0],
                                          (1-middle)*a[1]+middle*b[1]), uv_loops))
        _require(faces, 'original Member carrier leaves the original face material')
        intervals.append({'interval': [[low.numerator, low.denominator],
                                       [high.numerator, high.denominator]],
                          'material_faces': faces})
    endpoints = []
    for point in segment:
        faces = sorted(face_id for face_id, frame, a, b, uv_loops in coplanar
                       if _point_in_face(_chart_uv(frame, point), uv_loops))
        if not faces:
            faces = sorted(face_id for face_id, (_, _, xyz_loops) in charts.items()
                           if _on_boundary_xyz(point, xyz_loops))
        _require(faces, 'original Member carrier endpoint leaves the original face material')
        endpoints.append(faces)
    return {'endpoint_material_faces': endpoints,
            'interior_material_intervals': intervals}


def _current_edge_controls(current, edge):
    row = current['edges'][edge]
    _require(row['curve'] == {'type': 'straight'},
             'requires a literal Straight current carrier')
    controls = []
    for vertex in (row['start'], row['end']):
        _require(vertex in current['vertices'], 'current carrier vertex is unavailable')
        controls.append(tuple(Fraction(float(x))
                              for x in current['vertices'][vertex]['position']))
    _require(controls[0] != controls[1], 'requires a nondegenerate current carrier')
    return tuple(controls)



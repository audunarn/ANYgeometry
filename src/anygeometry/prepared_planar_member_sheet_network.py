"""Whole-document planar interior/boundary stiffener network owner receipt.

This is the additive planar interior-stiffener owner slice. It generalizes the
boundary-only member Sheet network without weakening it: the whole connected
Plane/literal-Straight document, arbitrary finite straight continuous Member
chains with unique source carriers both on the component boundary and in the
interior of original face material, exact edge-local point Attachments, and the
member-on-Sheet joints generated by the owner intersection application are all
accounted for and certified. It grants no beam discretization, load transfer,
solver, external-reference or publication authority.

Certification chain, in order:
1. Every source/current Sheet/Part/Member/use/Attachment/Junction of the one
   connected document is accounted for; unsupported kinds refuse.
2. Original Member material membership: each original carrier segment is
   proved, with exact rational arithmetic and a complete boundary-event
   decomposition (no sampled acceptance oracle), to lie inside the union of
   the closed original face materials, holes excluded.
3. Source ancestry: current carriers are exact restrictions of the original
   straight carriers under unchanged certified tolerances.
4. Exact affine endpoint residual bounds certify Member stations, point
   stations and generated joint stations; squared-norm convexity extends the
   two endpoint residuals to each whole claimed interval.
5. Generated member-on-Sheet joints: each member_on_face_boundary Attachment
   and its overlap Junction are re-derived against the live owner incidence
   contracts, and their target edge is proved to lie in the closed material of
   the authored root of every current face carrying it. A multi-Sheet overlap
   Junction must declare exactly the live sheets_using_edge inventory.
6. Generated member point contacts: each member_through_face Attachment is
   re-derived through the qualified original->current Member mapping and the
   immutable authored root material proof; its target face UV, source and
   current point stations must agree within the unchanged recorded owner
   tolerance, and its crossing/endpoint/multi_way Junction must declare
   exactly the complete participating Member and Sheet owner sets.

Generated records, IDs and provenance alone never establish source membership:
the geometry is re-derived from the immutable source/live snapshots every
time. Reserved boundaries (refused, not guessed): point-range member
attachments, member_on_sheet_intersection and member-on-face-interior
attachments, original Junctions, orientation references, curved Members and
non-planar supports. Original material certificates use only owned authored
Sheet faces, so orphan faces cannot connect a disconnected Member.
"""
